CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    display_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('teacher', 'student')),
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    email TEXT NOT NULL DEFAULT '',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_ci ON users (LOWER(email)) WHERE email <> '';

CREATE TABLE IF NOT EXISTS classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (teacher_id, name)
);
CREATE TABLE IF NOT EXISTS class_memberships (
    class_id BIGINT NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (class_id, student_id)
);

CREATE TABLE IF NOT EXISTS question_banks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id),
    content_hash TEXT NOT NULL UNIQUE,
    imported_count INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_id BIGINT REFERENCES question_banks(id) ON DELETE SET NULL,
    category TEXT NOT NULL,
    scope TEXT NOT NULL DEFAULT '',
    grade_level TEXT NOT NULL DEFAULT '',
    difficulty TEXT NOT NULL,
    question_type TEXT NOT NULL CHECK (question_type IN ('choice', 'fill_blank', 'essay')),
    prompt TEXT NOT NULL,
    options JSONB NOT NULL DEFAULT '[]'::jsonb,
    answer TEXT NOT NULL DEFAULT '',
    accepted_answers JSONB NOT NULL DEFAULT '[]'::jsonb,
    explanation TEXT NOT NULL DEFAULT '',
    rubric TEXT NOT NULL DEFAULT '',
    min_word_count INTEGER NOT NULL DEFAULT 0 CHECK (min_word_count >= 0),
    points INTEGER NOT NULL CHECK (points > 0),
    is_published BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS questions_practice_idx
    ON questions (is_published, category, difficulty);

CREATE TABLE IF NOT EXISTS assignment_sets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    starts_at TIMESTAMPTZ,
    due_at TIMESTAMPTZ,
    time_limit_minutes INTEGER NOT NULL DEFAULT 0,
    allow_retake BOOLEAN NOT NULL DEFAULT FALSE,
    show_answers BOOLEAN NOT NULL DEFAULT TRUE,
    status TEXT NOT NULL DEFAULT 'published'
        CHECK (status IN ('draft', 'published', 'closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS assignment_questions (
    assignment_id BIGINT NOT NULL REFERENCES assignment_sets(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    PRIMARY KEY (assignment_id, question_id)
);
CREATE TABLE IF NOT EXISTS assignment_students (
    assignment_id BIGINT NOT NULL REFERENCES assignment_sets(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (assignment_id, student_id)
);

CREATE TABLE IF NOT EXISTS quiz_sessions (
    id UUID PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question_ids JSONB NOT NULL,
    assignment_id BIGINT REFERENCES assignment_sets(id) ON DELETE SET NULL,
    status TEXT NOT NULL DEFAULT 'in_progress'
        CHECK (status IN ('in_progress', 'submitted')),
    score INTEGER NOT NULL DEFAULT 0,
    max_score INTEGER NOT NULL DEFAULT 0,
    correct_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    response TEXT NOT NULL DEFAULT '',
    earned_points INTEGER,
    feedback TEXT NOT NULL DEFAULT '',
    revision_requested BOOLEAN NOT NULL DEFAULT FALSE,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    quiz_id UUID REFERENCES quiz_sessions(id) ON DELETE SET NULL,
    assignment_id BIGINT REFERENCES assignment_sets(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS attempts_student_date_idx
    ON attempts (student_id, submitted_at DESC);
CREATE TABLE IF NOT EXISTS essay_drafts (
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    content TEXT NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (student_id, question_id)
);
CREATE TABLE IF NOT EXISTS essay_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
    version_number INTEGER NOT NULL,
    content TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'submitted'
        CHECK (status IN ('submitted', 'graded', 'revision_requested')),
    score INTEGER,
    feedback TEXT NOT NULL DEFAULT '',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (attempt_id, version_number)
);

CREATE TABLE IF NOT EXISTS daily_login_rewards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    login_date DATE NOT NULL,
    streak_day INTEGER NOT NULL CHECK (streak_day > 0),
    points_awarded INTEGER NOT NULL CHECK (points_awarded IN (15, 30, 50)),
    free_wheel_awarded BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (student_id, login_date)
);
CREATE TABLE IF NOT EXISTS wheel_spins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    request_id TEXT NOT NULL,
    wheel_type TEXT NOT NULL CHECK (wheel_type IN ('standard', 'milestone', 'streak')),
    score_milestone INTEGER,
    streak_day INTEGER,
    points_spent INTEGER NOT NULL DEFAULT 150,
    points_awarded INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (student_id, request_id),
    UNIQUE (student_id, score_milestone),
    UNIQUE (student_id, streak_day),
    CHECK (
        (wheel_type = 'standard' AND score_milestone IS NULL AND streak_day IS NULL
         AND points_spent = 150 AND points_awarded IN (10, 20, 30, 40, 50))
        OR
        (wheel_type = 'milestone' AND score_milestone IS NOT NULL AND streak_day IS NULL
         AND points_spent = 150 AND points_awarded IN (30, 40, 50, 60, 70))
        OR
        (wheel_type = 'streak' AND score_milestone IS NULL AND streak_day IS NOT NULL
         AND points_spent = 0 AND points_awarded IN (10, 20, 30, 40, 50))
    )
);

CREATE TABLE IF NOT EXISTS announcements (
